// Reference vectors for the Swift port of src/hexgrid.js.
//
// The hex maths is the one part of this app where the Swift and the JavaScript
// must agree exactly rather than approximately: a cell id is a string the
// server already has rows for, so a port that is one column out at some
// latitude does not draw a slightly wrong map — it fails to find the cells the
// map is made of.
//
// So the Swift tests do not assert against numbers anyone typed. They assert
// against this file's output, taken from the JavaScript that wrote the database.
// Re-run after changing src/hexgrid.js:
//
//   node HexPlore/Tools/gen-hex-vectors.mjs
//
// It rewrites HexploreCore/Tests/HexploreCoreTests/HexGridVectors.swift.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  BASE_COLS,
  MAX_LEVEL,
  R0,
  WORLD,
  cellCenter,
  colsOf,
  latOf,
  lngOf,
  mercX,
  mercY,
  normCol,
  parentOf,
  pointToCell,
  radiusOf,
} from '../../HexPlore-webserver/src/hexgrid.js';

const here = dirname(fileURLToPath(import.meta.url));

// A spread chosen to exercise the things that actually differ between the two
// languages: both hemispheres, both signs of longitude, the Mercator clamp at
// the poles, and either side of the antimeridian where the column wraps.
const PLACES = [
  ['equator/prime meridian', 0, 0],
  ['Bern', 46.948, 7.4474],
  ['Zermatt', 46.0207, 7.7491],
  ['Reykjavik', 64.1466, -21.9426],
  ['Sydney', -33.8688, 151.2093],
  ['Lisbon', 38.7223, -9.1393],
  ['Ushuaia', -54.8019, -68.303],
  ['just west of the antimeridian', 0, 179.999],
  ['just east of the antimeridian', 0, -179.999],
  ['exactly the antimeridian', 12.34, 180],
  ['Mercator north clamp', 85.05112878, 0],
  ['Mercator south clamp', -85.05112878, 0],
  ['a southern negative-column case', -33.8688, -70.6693],
];

const f = (n) => {
  if (Number.isInteger(n)) return `${n}.0`;
  // Swift parses the same shortest-round-trip literal JS prints.
  return String(n);
};

const lines = [];
const push = (s = '') => lines.push(s);

push('// Generated by HexPlore/Tools/gen-hex-vectors.mjs — do not edit by hand.');
push('//');
push('// Every expectation here was produced by running the JavaScript in');
push('// src/hexgrid.js, which is what wrote the cell ids in the database. The');
push('// Swift port is correct exactly insofar as it reproduces these.');
push();
push('enum HexGridVectors {');

// --- Constants ----------------------------------------------------------------
push('    /// Constants, as the JavaScript computes them.');
push('    enum Constants {');
push(`        static let maxLevel = ${MAX_LEVEL}`);
push(`        static let baseCols = ${BASE_COLS}`);
push(`        static let world = ${f(WORLD)}`);
push(`        static let radius0 = ${f(R0)}`);
push('    }');
push();

// --- radiusOf / colsOf per level ----------------------------------------------
push('    /// (level, radius, columns) at every level.');
push('    static let levels: [(level: Int, radius: Double, cols: Int)] = [');
for (let L = 0; L <= MAX_LEVEL; L++) {
  push(`        (${L}, ${f(radiusOf(L))}, ${colsOf(L)}),`);
}
push('    ]');
push();

// --- Mercator projection ------------------------------------------------------
push('    /// (name, lat, lng, mercX, mercY) — the forward projection.');
push('    static let projections: [(name: String, lat: Double, lng: Double, x: Double, y: Double)] = [');
for (const [name, lat, lng] of PLACES) {
  push(`        ("${name}", ${f(lat)}, ${f(lng)}, ${f(mercX(lng))}, ${f(mercY(lat))}),`);
}
push('    ]');
push();

// --- Inverse projection -------------------------------------------------------
push('    /// (mercX, mercY, lng, lat) — the inverse, taken from the forward output.');
push('    static let inverses: [(x: Double, y: Double, lng: Double, lat: Double)] = [');
for (const [, lat, lng] of PLACES) {
  const x = mercX(lng);
  const y = mercY(lat);
  push(`        (${f(x)}, ${f(y)}, ${f(lngOf(x))}, ${f(latOf(y))}),`);
}
push('    ]');
push();

// --- pointToCell at every level ------------------------------------------------
push('    /// (name, level, lat, lng, col, row) — a point resolved to its cell.');
push('    static let pointCells: [(name: String, level: Int, lat: Double, lng: Double, col: Int, row: Int)] = [');
for (const [name, lat, lng] of PLACES) {
  for (let L = 0; L <= MAX_LEVEL; L++) {
    const [c, r] = pointToCell(L, mercX(lng), mercY(lat));
    push(`        ("${name}", ${L}, ${f(lat)}, ${f(lng)}, ${c}, ${r}),`);
  }
}
push('    ]');
push();

// --- Canonical cell ids ---------------------------------------------------------
// The string the server stores. Built exactly as cellIdAt() in src/main.js does.
push('    /// (name, level, lat, lng, id) — the canonical id string the server keys on.');
push('    static let cellIds: [(name: String, level: Int, lat: Double, lng: Double, id: String)] = [');
for (const [name, lat, lng] of PLACES) {
  for (let L = 0; L <= MAX_LEVEL; L++) {
    const [c, r] = pointToCell(L, mercX(lng), mercY(lat));
    const id = `${L}/${normCol(c, colsOf(L))}/${r}`;
    push(`        ("${name}", ${L}, ${f(lat)}, ${f(lng)}, "${id}"),`);
  }
}
push('    ]');
push();

// --- cellCenter ------------------------------------------------------------------
push('    /// (level, col, row, x, y) — a cell resolved back to its Mercator centre.');
push('    static let centers: [(level: Int, col: Int, row: Int, x: Double, y: Double)] = [');
for (const [, lat, lng] of PLACES) {
  for (let L = 0; L <= MAX_LEVEL; L++) {
    const [c, r] = pointToCell(L, mercX(lng), mercY(lat));
    const [x, y] = cellCenter(L, c, r);
    push(`        (${L}, ${c}, ${r}, ${f(x)}, ${f(y)}),`);
  }
}
push('    ]');
push();

// --- parentOf ---------------------------------------------------------------------
// The roll-up that lights a country from one visited cell.
push('    /// (level, col, row, parentCol, parentRow) — the coarse cell containing this one.');
push('    static let parents: [(level: Int, col: Int, row: Int, parentCol: Int, parentRow: Int)] = [');
for (const [, lat, lng] of PLACES) {
  for (let L = 0; L < MAX_LEVEL; L++) {
    const [c, r] = pointToCell(L, mercX(lng), mercY(lat));
    const [pc, pr] = parentOf(L, c, r);
    push(`        (${L}, ${c}, ${r}, ${pc}, ${pr}),`);
  }
}
push('    ]');
push();

// --- normCol ------------------------------------------------------------------------
// Negative and out-of-range columns are the antimeridian case, and the one place
// JavaScript's % and a naive Swift % disagree.
push('    /// (col, n, normalized) — including the negative columns that wrap.');
push('    static let normalizedColumns: [(col: Int, n: Int, expected: Int)] = [');
for (const n of [colsOf(0), colsOf(MAX_LEVEL)]) {
  for (const col of [0, 1, -1, n, n + 1, -n, -n - 1, 2 * n + 5, -(2 * n + 5)]) {
    push(`        (${col}, ${n}, ${normCol(col, n)}),`);
  }
}
push('    ]');

// --- Math.round semantics ----------------------------------------------------------
// The one behaviour the two languages genuinely disagree about. Generated rather
// than typed so the Swift is checked against what Math.round actually does.
push('    /// (input, Math.round(input)) — JavaScript rounds a half toward +∞,');
push('    /// where Swift\'s own .rounded() rounds a half away from zero.');
push('    static let roundings: [(input: Double, expected: Double)] = [');
for (const v of [0.5, -0.5, 1.5, -1.5, 2.5, -2.5, 0.4, -0.4, 0.6, -0.6, 3.49, -3.49, 3.51, -3.51, 0]) {
  push(`        (${f(v)}, ${f(Math.round(v))}),`);
}
push('    ]');

push('}');

const out = join(here, '..', 'HexploreCore', 'Tests', 'HexploreCoreTests', 'HexGridVectors.swift');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
console.log(`  ${PLACES.length} places × ${MAX_LEVEL + 1} levels`);
