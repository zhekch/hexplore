// English — the source language, and the fallback for every other one.
//
// Every key the app can ask for is defined here, and that is the rule the tests
// enforce: `scripts/test/i18n.mjs` walks index.html for every `data-i18n`
// attribute and the source for every `t('…')` call, and fails if either asks
// for something this file does not have. A missing key renders as the key
// itself, which is deliberately ugly — a key on screen is a bug and should look
// like one — but it should never get as far as a browser.
//
// ## How the keys are named
//
// `<where>.<what>`, where *where* is the nearest enclosing element with an id
// and *what* is a slug of the English text. That is not elegant, and it is the
// property that matters: a key can be found from the string on screen and from
// the markup that holds it, with no lookup table in between. Most of these were
// generated from the markup for exactly that reason — 384 hand-written keys is
// 384 chances to file one under the wrong dialog.
//
// Keys under a bare module name (`snow.`, `whatsNew.`, `export.`) come from
// JavaScript, where there is no enclosing id to name them by.
//
// ## For translators
//
// `{name}` placeholders are filled in at runtime and must survive into the
// translation, spelled the same. They may be reordered freely — that is why they
// are named rather than positional, because a count and its noun do not come in
// the same order in every language.
//
// Nothing here is HTML. These are set with `textContent`, so a tag in one would
// appear on screen as a tag.

