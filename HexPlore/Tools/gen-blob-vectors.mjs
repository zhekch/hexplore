// Reference vectors for the Swift/Metal port of the blob shaping curve.
//
// `alphaLut` is what decides a blob's outline: the blurred sheet is mapped
// through a smoothstep centred on BLOB_LEVEL, and where that curve puts the
// half-way point is where the edge of the shape is. A Metal shader that
// disagrees with it by a few percent does not look like a bug — it looks like
// slightly different blobs, which is exactly the kind of wrong nobody catches.
//
// So the Swift asserts against this, taken from the real function:
//
//   node HexPlore/Tools/gen-blob-vectors.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  ALPHA_FLOOR,
  BLOB_ALPHA,
  BLOB_BLUR,
  BLOB_EDGE,
  BLOB_FEATHER_PX,
  BLOB_HEAT_ALPHA,
  BLOB_HEAT_EDGE,
  BLOB_HEAT_FEATHER_PX,
  BLOB_LEVEL,
  BLOB_ROUNDS,
  alphaLut,
} from '../../src/blob-canvas.js';

const here = dirname(fileURLToPath(import.meta.url));

// The three edge widths the app actually uses: the single-colour wash, the heat
// maps, and the tight band the intermediate shaping rounds run at.
const EDGES = [
  ['single', BLOB_EDGE],
  ['heat', BLOB_HEAT_EDGE],
  ['shaping', 0.1], // SHAPE_EDGE, which is module-private and not a look knob
];

const f = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

const lines = [];
const push = (s = '') => lines.push(s);

push('// Generated by HexPlore/Tools/gen-blob-vectors.mjs — do not edit by hand.');
push('//');
push('// Produced by running the real `alphaLut` from src/blob-canvas.js.');
push();
push('enum BlobVectors {');

push('    /// The tuning constants, as the JavaScript declares them.');
push('    enum Constants {');
push(`        static let blur = ${f(BLOB_BLUR)}`);
push(`        static let rounds = ${BLOB_ROUNDS}`);
push(`        static let level = ${f(BLOB_LEVEL)}`);
push(`        static let alphaFloor = ${f(ALPHA_FLOOR)}`);
push(`        static let edge = ${f(BLOB_EDGE)}`);
push(`        static let heatEdge = ${f(BLOB_HEAT_EDGE)}`);
push(`        static let featherPx = ${f(BLOB_FEATHER_PX)}`);
push(`        static let heatFeatherPx = ${f(BLOB_HEAT_FEATHER_PX)}`);
push(`        static let alpha = ${f(BLOB_ALPHA)}`);
push(`        static let heatAlpha = ${f(BLOB_HEAT_ALPHA)}`);
push('    }');
push();

// The whole curve, all 256 entries, for each edge width. It is only 768 bytes
// of expectation and it pins the shape exactly rather than at sampled points.
for (const [name, edge] of EDGES) {
  const lut = alphaLut(edge);
  push(`    /// alphaLut(${edge}) — the "${name}" edge, all 256 entries.`);
  push(`    static let ${name}Lut: [UInt8] = [`);
  for (let i = 0; i < 256; i += 16) {
    push('        ' + Array.from(lut.slice(i, i + 16)).join(', ') + ',');
  }
  push('    ]');
  push();
}

push('    /// (edge, input, expected) — the same curve, as loose samples, so a');
push('    /// failure names the input that broke rather than a whole array.');
push('    static let samples: [(edge: Double, input: Int, expected: Int)] = [');
for (const [, edge] of EDGES) {
  const lut = alphaLut(edge);
  for (const a of [0, 1, 12, 13, 32, 64, 76, 77, 90, 128, 150, 200, 254, 255]) {
    push(`        (${f(edge)}, ${a}, ${lut[a]}),`);
  }
}
push('    ]');

push('}');

const out = join(here, '..', 'HexploreCore', 'Tests', 'HexploreCoreTests', 'BlobVectors.swift');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
console.log(`  ${EDGES.length} edge widths × 256 entries`);
