#!/usr/bin/env node
// Which continent each country belongs to, from the same Natural Earth admin-0
// file src/countries.json is built from, written to src/continent-map.js.
//
//   node scripts/build-continents.mjs      (or: npm run build:continents)
//
// Only the membership is stored — the continent *shapes* are the union of the
// country shapes we already ship, built in the browser. Committing a second set
// of outlines would be a few hundred KB saying what countries.json already
// says, and any disagreement between the two would show as a sliver of ocean
// along a coast at one zoom level and not the next.
//
// A .js module rather than the .json the other datasets are, for two reasons
// that both come from it being 4 KB instead of 4 MB: it wants to be *imported*,
// not fetched — every other dataset here is dynamic-imported so a phone-sized
// session never pays for it, and this one is small enough to sit in the bundle
// and answer synchronously — and plain Node reads a .js module without the
// import attribute that JSON needs and Vite doesn't want (the same wrinkle
// loadCountries' `data` parameter exists for). Grouped by continent so a
// re-run's diff says which country moved rather than reflowing 240 lines.
//
// Joined on ADM0_A3, never on the country name: the same reason countries.json
// carries an ISO code (see scripts/build-countries.mjs).
//
// Re-run only when refreshing the boundary data — the output is committed so
// normal installs don't need network access.

import { writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src', 'continent-map.js');
const countriesFile = path.join(root, 'src', 'countries.json');

console.log(`Fetching ${SRC} …`);
const res = await fetch(SRC);
if (!res.ok) {
  console.error(`Download failed: ${res.status} ${res.statusText}`);
  process.exit(1);
}
const geo = await res.json();

// Natural Earth files eight of the countries we draw under "Seven seas (open
// ocean)", which is not a continent — it is the leftovers. Three of them are
// sovereign states somebody can spend a fortnight in, and leaving them out
// would mean a holiday in the Maldives lit nothing at all at this level and
// went uncounted at every other. Placed the way the UN's M49 scheme does, with
// the polar leftovers going to Antarctica rather than to the nearest landmass.
const OCEAN_ISLANDS = {
  MUS: 'Africa', // Mauritius
  SYC: 'Africa', // Seychelles
  SHN: 'Africa', // Saint Helena
  IOT: 'Africa', // British Indian Ocean Territory
  MDV: 'Asia', // Maldives
  SGS: 'Antarctica', // South Georgia and the South Sandwich Islands
  ATF: 'Antarctica', // French Southern and Antarctic Lands
  HMD: 'Antarctica', // Heard Island and McDonald Islands
};

const byIso = {};
for (const f of geo.features) {
  const p = f.properties;
  const iso = p.ADM0_A3 ?? p.ISO_A3 ?? p.SOV_A3 ?? null;
  const continent = p.CONTINENT ?? null;
  if (!iso || !continent) continue;
  const placed = continent.startsWith('Seven seas') ? OCEAN_ISLANDS[iso] : continent;
  if (placed) byIso[iso] = placed;
}

// Every country we actually draw has to be placed, or it would sit unlit inside
// a continent it belongs to and read as a hole.
const countries = JSON.parse(await readFile(countriesFile, 'utf8'));
const missing = countries.filter((c) => c.iso && !byIso[c.iso]).map((c) => `${c.iso} ${c.id}`);

const grouped = new Map();
for (const [iso, name] of Object.entries(byIso)) {
  if (!grouped.has(name)) grouped.set(name, []);
  grouped.get(name).push(iso);
}
const names = [...grouped.keys()].sort();
const body = names
  .map((name) => `  ${JSON.stringify(name)}: [${grouped.get(name).sort().map((i) => `'${i}'`).join(', ')}],`)
  .join('\n');

writeFileSync(
  outFile,
  `// Generated by scripts/build-continents.mjs from Natural Earth's admin-0 file.
// Do not edit by hand — re-run the script instead. Keyed by ADM0_A3, the same
// code src/countries.json carries, because the two files disagree on names.
export default {
${body}
};
`,
);

const counts = new Map();
for (const c of countries) {
  const k = c.iso ? byIso[c.iso] : null;
  if (k) counts.set(k, (counts.get(k) ?? 0) + 1);
}
console.log(`${Object.keys(byIso).length} codes → ${path.relative(root, outFile)}`);
for (const [name, n] of [...counts].sort((a, b) => b[1] - a[1])) console.log(`  ${name}: ${n} drawn`);
if (missing.length) console.warn(`Unplaced (drawn but no continent): ${missing.join(', ')}`);
